<?php declare(strict_types=1);
require __DIR__.'/LookingGlass.php';
require __DIR__.'/config.php';
require __DIR__.'/iperf-manager.php';

Hybula\LookingGlass::startSession();
header('Content-Type: application/json; charset=UTF-8');
header('Cache-Control: no-store');
header('X-Content-Type-Options: nosniff');
if (!LG_BLOCK_SPEEDTEST) { http_response_code(404); exit; }

try {
    $method = $_SERVER['REQUEST_METHOD'] ?? 'GET';
    $job = isset($_SESSION['iperf_job']) ? iperfReadJob($_SESSION['iperf_job']) : null;
    if ($job && in_array($job['status'], ['starting', 'running'], true) && time() > $job['createdAt'] + 75) {
        $job['status'] = 'error'; $job['expiresAt'] = 0;
        $job['message'] = 'The iPerf3 worker ended. Start a new server.';
        iperfWriteJob($job);
    }
    if ($method === 'POST') {
        $csrf = $_SERVER['HTTP_X_CSRF_TOKEN'] ?? '';
        if (empty($_SESSION['iperf_csrf']) || !hash_equals($_SESSION['iperf_csrf'], $csrf)) {
            http_response_code(403); echo json_encode(['error' => 'Refresh the page and retry.']); exit;
        }
        if ((int)($_SERVER['CONTENT_LENGTH'] ?? 0) > 4096) { http_response_code(413); exit; }
        $action = json_decode((string)file_get_contents('php://input'), true)['action'] ?? '';
        if ($action === 'start') {
            if (!$job || !in_array($job['status'], ['starting', 'running'], true)) {
                // Remove only expired files generated by this manager.
                foreach (glob(iperfJobDirectory().'/*.json') ?: [] as $old) {
                    if (filemtime($old) < time() - 3600 && preg_match('/[a-f0-9]{32}\.json$/D', $old)) {
                        @unlink($old.'.stop'); @unlink($old);
                    }
                }
                $id = bin2hex(random_bytes(16));
                $job = ['id' => $id, 'status' => 'starting', 'port' => 0, 'log' => '',
                    'createdAt' => time(), 'expiresAt' => 0, 'message' => 'Starting server…'];
                iperfWriteJob($job);
                $_SESSION['iperf_job'] = $id;
                $command = 'nohup '.escapeshellarg(PHP_BINDIR.'/php').' '.escapeshellarg(__DIR__.'/iperf-worker.php').' '.escapeshellarg($id).' </dev/null >/dev/null 2>&1 &';
                $process = proc_open(['sh', '-c', $command], [0 => ['file', '/dev/null', 'r'], 1 => ['file', '/dev/null', 'w'], 2 => ['file', '/dev/null', 'w']], $pipes);
                if (!is_resource($process) || proc_close($process) !== 0) { throw new RuntimeException('Unable to start iPerf3 worker.'); }
            }
        } elseif ($action === 'stop') {
            if ($job && in_array($job['status'], ['starting', 'running'], true)) {
                touch(iperfJobPath($job['id']).'.stop');
            }
        } else { http_response_code(400); echo json_encode(['error' => 'Invalid action.']); exit; }
    } elseif ($method !== 'GET') { header('Allow: GET, POST'); http_response_code(405); exit; }
    session_write_close();
    echo json_encode(iperfPublicJob($job), JSON_INVALID_UTF8_SUBSTITUTE | JSON_UNESCAPED_SLASHES);
} catch (Throwable $error) {
    http_response_code(500);
    echo json_encode(['error' => 'The iPerf3 service could not complete this request.']);
}
